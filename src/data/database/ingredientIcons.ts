/**
 * Returns the exact transparent 3D PNG icon path for any ING_* code or free-text Persian/English item name.
 */
export function getIngredientIconPath(ingredientIdOrCode?: string, nameFa?: string): string {
  if (ingredientIdOrCode && CODE_TO_ICON_KEY[ingredientIdOrCode]) {
    return INGREDIENT_ICON_PATHS[CODE_TO_ICON_KEY[ingredientIdOrCode]];
  }
  const probe = `${ingredientIdOrCode ?? ''} ${nameFa ?? ''}`;
  for (const [regex, key] of NAME_FALLBACK_RULES) {
    if (regex.test(probe)) {
      return INGREDIENT_ICON_PATHS[key];
    }
  }
  return INGREDIENT_ICON_PATHS.saffron_spices;
}
